"""Scalar-denominator contact evaluation inverses, with coherent TM errors.

The universal polynomial inverse is generated by analytic orbit interpolation
and exact rational-function cancellation. No stored inverse table, numerical
matrix inverse or matrix Neumann test is used. Scalar reciprocal remainder
checks remain mandatory.
"""
from fractions import Fraction
from math import comb

from taylor_models import TM, ORDER, iv
from matrix_models import MT
from ipoly import IP
from generated_inverse import generated_pattern, POINTS


def _coefficient(encoded):
    n, d, r, q = encoded
    return (Fraction(n, d), Fraction(r, q))


def _shift(encoded, center):
    """Exact coefficients after substituting a=center+u in Q(sqrt(2))[a]."""
    coefficients = [_coefficient(c) for c in encoded]
    output = []
    for j in range(len(coefficients)):
        rational = irrational = Fraction(0)
        for k in range(j, len(coefficients)):
            scale = comb(k, j) * center ** (k - j)
            rational += coefficients[k][0] * scale
            irrational += coefficients[k][1] * scale
        output.append((rational, irrational))
    return output


def _evaluate_shifted(encoded, center, powers, sqrt2):
    coefficients = [iv.mpf(q) + iv.mpf(r) * sqrt2
                    for q, r in _shift(encoded, center)]
    c = [sum((q * powers[j].c[k] for j, q in enumerate(coefficients)), iv.mpf(0))
         for k in range(ORDER + 1)]
    error = sum((abs(q).b * powers[j].e for j, q in enumerate(coefficients)), iv.mpf(0))
    return TM(c, error)


_LAST = None


def evaluation_inverse_model(A, pivot_monomials, ordered_triples):
    """An IP model of the exact 21x21 contact evaluation inverse."""
    global _LAST
    monomials = tuple(tuple(e) for e in pivot_monomials)
    points = tuple(tuple(t) for t in ordered_triples)
    if points != POINTS:
        raise ArithmeticError("Analytic inverse evaluation row order mismatch")
    if _LAST is not None and _LAST[0] is A and _LAST[1] == monomials:
        return _LAST[2]
    pattern = generated_pattern(monomials, points)

    # The center is merely an exact dyadic algebraic recentering choice.
    center = Fraction.from_float(float(A.c[0]))
    U = A - TM.const(iv.mpf(center))
    powers = [TM.const(1)]
    for _ in range(14):
        powers.append(powers[-1] * U)
    sqrt2 = iv.sqrt(2)
    # Preserve factorization to avoid cancellation in the scalar denominator.
    factors = [A, (A - 1) ** 2, 5 * A - 1,
               17 * A ** 2 - 10 * A + 1,
               7 * A ** 2 + 2 * A - 1,
               13 * A ** 2 - 6 * A + 1,
               599 * A ** 4 - 292 * A ** 3 + 2 * A ** 2 + 12 * A - 1]
    reciprocal = TM.const(1)
    for factor in factors:
        reciprocal = reciprocal * factor.inverse()
    entries = [[_evaluate_shifted(encoded, center, powers, sqrt2) * reciprocal
                for encoded in row] for row in pattern["numerators"]]
    result = IP.fromMT(MT.from_scalars(entries))
    _LAST = (A, monomials, result)
    return result
